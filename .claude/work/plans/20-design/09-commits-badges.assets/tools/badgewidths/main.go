// Command badgewidths generates internal/badges/widths_gen.go from DejaVu Sans (Bitstream Vera licence, see
// font/LICENSE-DejaVu.txt). It lives in the nested tools module so x/image never enters the product's module graph.
//
//	go run ./badgewidths -font badgewidths/font/DejaVuSans.ttf -out ../internal/badges/widths_gen.go
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"

	"golang.org/x/image/font"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/font/sfnt"
	"golang.org/x/image/math/fixed"
)

// wantSHA256 is ttf/DejaVuSans.ttf of dejavu-fonts-ttf-2.37.tar.bz2 (archive sha256 fa9ca4d13871dd122f61258a80d01751d603b4d3ee14095d65453b4e846e17d7,
// https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.tar.bz2; name table: "Version 2.37").
const wantSHA256 = "7da195a74c55bef988d0d48f9508bd5d849425c1770dba5d7bfc6ce9ed848954"

type rng struct{ lo, hi rune }

// Ranges covered by the table, in index order: printable ASCII and Latin-1 Supplement plus Latin Extended-A
// (Western and Central European text, including Norwegian letters). Everything else is estimated at run time.
var ranges = []rng{{0x20, 0x7E}, {0xA0, 0x17F}}

func main() {
	fontPath := flag.String("font", "badgewidths/font/DejaVuSans.ttf", "DejaVuSans.ttf")
	out := flag.String("out", "", "output Go file")
	flag.Parse()
	b, err := os.ReadFile(*fontPath)
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(b)
	if got := hex.EncodeToString(sum[:]); got != wantSHA256 {
		log.Fatalf("font sha256 %s, want %s (a different font would silently change every badge width)", got, wantSHA256)
	}
	f, err := opentype.Parse(b)
	if err != nil {
		log.Fatal(err)
	}
	upem := int(f.UnitsPerEm())
	var sb sfnt.Buffer
	var table []byte
	var sumLetters, nLetters int
	for _, r := range ranges {
		for c := r.lo; c <= r.hi; c++ {
			gi, err := f.GlyphIndex(&sb, c)
			if err != nil || gi == 0 {
				log.Fatalf("no glyph for U+%04X: %v", c, err)
			}
			// at ppem == units-per-em one pixel is one font unit, so the 26.6 result is units<<6 exactly
			adv, err := f.GlyphAdvance(&sb, gi, fixed.I(upem), font.HintingNone)
			if err != nil {
				log.Fatal(err)
			}
			v := int(adv) >> 6
			if v < 0 || v > 0xFFFF {
				log.Fatalf("advance out of range for U+%04X: %d", c, v)
			}
			table = append(table, byte(v>>8), byte(v))
			if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') {
				sumLetters += v
				nLetters++
			}
		}
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/badgewidths from DejaVu Sans 2.37 (sha256 %s); DO NOT EDIT.\n\n", wantSHA256)
	fmt.Fprintf(&buf, "package badges\n\n")
	fmt.Fprintf(&buf, "// Advance widths in font units (%d per em), big endian uint16 per code point, ranges in order:\n", upem)
	fmt.Fprintf(&buf, "// U+0020..U+007E, U+00A0..U+017F. The table is metric data derived from the font, not the font.\n")
	fmt.Fprintf(&buf, "const widthTable = \"")
	for _, x := range table {
		fmt.Fprintf(&buf, "\\x%02x", x)
	}
	fmt.Fprintf(&buf, "\"\n\n")
	fmt.Fprintf(&buf, "const (\n\twidthUnitsPerEm = %d\n\twidthAverage    = %d // mean advance of [A-Za-z0-9], used for code points outside the table\n", upem, sumLetters/nLetters)
	fmt.Fprintf(&buf, "\twidthWide       = %d // one em: estimate for East Asian wide and fullwidth characters\n)\n", upem)
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if *out == "" {
		os.Stdout.Write(src)
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
