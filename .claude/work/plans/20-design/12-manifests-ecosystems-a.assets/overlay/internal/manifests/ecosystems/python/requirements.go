const maxLogicalLine = 64 << 10

// requirements parses requirements*.txt and constraints*.txt. It is one implementation behind two parser ids because a parser cannot read its
// own file name (path independence): the constraints parser only changes the Kind of the result.
type requirements struct {
	base
	constraints bool
}

// NewRequirements returns the requirements-file parser (requirements*.txt, requirements*.in, requirements/*.txt).
func NewRequirements() manifests.Parser {
	return requirements{base: base{id: RequirementsID, match: matchRequirements, kind: manifests.KindManifest}}
}

// NewConstraints returns the constraints-file parser (constraints*.txt, constraints*.in); its Parsed has Kind KindCatalog.
func NewConstraints() manifests.Parser {
	return requirements{base: base{id: ConstraintsID, match: matchConstraints, kind: manifests.KindCatalog}, constraints: true}
}

type logicalLine struct {
	text     string
	line     int
	comments []string // physical comment lines directly following (pip-compile "# via")
}

// joinLines applies pip's rules: backslash continuation, full-line and trailing " #" comments.
func joinLines(data []byte) []logicalLine {
	raw := strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")
	var out []logicalLine
	for i := 0; i < len(raw); i++ {
		start := i + 1
		line := raw[i]
		if strings.HasSuffix(line, "\\") && i+1 < len(raw) && countTrailingBackslashes(line)%2 == 1 {
			// continuation: build linearly and cap the logical line (a 200,000-line continuation chain took 2 s with concatenation)
			var b strings.Builder
			cur := line
			for strings.HasSuffix(cur, "\\") && i+1 < len(raw) && countTrailingBackslashes(cur)%2 == 1 {
				if b.Len() < maxLogicalLine {
					b.WriteString(strings.TrimSuffix(cur, "\\"))
					b.WriteByte(' ')
				}
				i++
				cur = strings.TrimSpace(raw[i])
			}
			if b.Len() < maxLogicalLine {
				b.WriteString(cur)
			}
			line = b.String()
		}
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(trim, "#") {
			if len(out) > 0 {
				out[len(out)-1].comments = append(out[len(out)-1].comments, trim)
			}
			continue
		}
		if trim == "" {
			continue
		}
		if j := strings.Index(line, " #"); j >= 0 {
			line = line[:j]
		}
		out = append(out, logicalLine{text: strings.TrimSpace(line), line: start})
	}
	return out
}

func countTrailingBackslashes(s string) int {
	n := 0
	for i := len(s) - 1; i >= 0 && s[i] == '\\'; i-- {
		n++
	}
	return n
}

var (
	pipCompileHeader = regexp.MustCompile(`(?i)autogenerated by (pip-compile|uv)\b|uv pip compile`)
	eggFragment      = regexp.MustCompile(`[#&]egg=([A-Za-z0-9][A-Za-z0-9._-]*)`)
	wheelName        = regexp.MustCompile(`/([A-Za-z0-9][A-Za-z0-9._]*?)-[0-9][^/-]*(-[^/]*)*\.(whl|tar\.gz|zip)$`)
)

func (p requirements) Parse(ctx context.Context, f manifests.File, lim manifests.Limits) (manifests.Parsed, error) {
	data, rej := p.admit(f, lim)
	if rej != nil {
		return *rej, nil
	}
	out := manifests.Parsed{Kind: manifests.KindManifest}
	if p.constraints {
		out.Kind = manifests.KindCatalog
	}
	head := string(data)
	if len(head) > 1024 {
		head = head[:1024]
	}
	lockMode := pipCompileHeader.MatchString(head)
	if lockMode {
		out.Kind = manifests.KindLockfile
	}
	ignored := map[string]bool{}
	lines := joinLines(data)
	if len(lines) > 200000 {
		lines = lines[:200000]
		out.Diagnostics = append(out.Diagnostics, diag("limit.nodes", 0, "more than 200000 lines; the rest was not read"))
	}
	out.Properties = map[string]string{}
	g := limits.NewGuard(ctx, lim)
	for _, ll := range lines {
		if err := g.Node(); err != nil {
			if ctx.Err() != nil {
				return manifests.Parsed{}, ctx.Err()
			}
			out.Diagnostics = append(out.Diagnostics, diag("limit.nodes", ll.line, "too many lines; the rest was not read"))
			break
		}
		text := ll.text
		if strings.Contains(text, "${") {
			out.Diagnostics = append(out.Diagnostics, diag("python.env-var", ll.line, "environment variable reference left unexpanded"))
		}
		if strings.HasPrefix(text, "-") {
			opt, arg := splitOption(text)
			switch opt {
			case "-r", "--requirement", "-c", "--constraint":
				kind := "r"
				if opt == "-c" || opt == "--constraint" {
					kind = "c"
				}
				if arg == "" || strings.Contains(arg, "://") {
					out.Diagnostics = append(out.Diagnostics, diag("python.include-outside-repo", ll.line, "include %q is not a repository path", manifests.CleanText(arg, 80)))
					continue
				}
				if rel, ok := repopath.Rel(arg); ok { // relative to this file; resolved by the assembler among the candidate files
					out.Properties[map[string]string{"r": "include:", "c": "constraint:"}[kind]+rel] = kind
					if !slices.Contains(out.Includes, rel) {
						out.Includes = append(out.Includes, rel)
					}
				} else {
					out.Diagnostics = append(out.Diagnostics, diag("python.include-outside-repo", ll.line, "include %q is absolute or malformed", manifests.CleanText(arg, 80)))
				}
				continue
			case "-e", "--editable":
				text = arg
			default:
				if !ignored[opt] && len(ignored) < 10 {
					ignored[opt] = true
					out.Diagnostics = append(out.Diagnostics, diag("python.option-ignored", ll.line, "option %s ignored", manifests.CleanText(opt, 40)))
				}
				continue
			}
		}
		// trailing per-requirement options (--hash=..., --global-option ...)
		hash := ""
		if j := strings.Index(text, " --"); j >= 0 {
			rest := text[j:]
			text = strings.TrimSpace(text[:j])
			if k := strings.Index(rest, "--hash="); k >= 0 {
				if f := strings.Fields(rest[k+len("--hash="):]); len(f) > 0 {
					hash = f[0]
				}
			}
		}
		d, ok := requirementLine(&out, ll.line, text)
		if !ok {
			continue
		}
		if lockMode {
			via := parseVia(ll.comments)
			lc := manifests.LockedComponent{ID: d.Target, Display: d.TargetDisplay(), Version: d.Version, Relationship: manifests.RelTransitive, Scope: manifests.ScopeUnknown, Integrity: manifests.CleanText(hash, 120), Loc: manifests.Location{Line: int(d.Line)}}
			for _, v := range via {
				if strings.HasPrefix(v, "-r ") {
					lc.Relationship = manifests.RelDirect
				}
			}
			if d.Version == "" && d.Source == manifests.SourceRegistry {
				continue
			}
			out.Locked = append(out.Locked, lc)
			continue
		}
		out.Dependencies = append(out.Dependencies, d)
	}
	if len(out.Properties) == 0 {
		out.Properties = nil
	}
	sort.SliceStable(out.Locked, func(i, j int) bool { return out.Locked[i].Loc.Line < out.Locked[j].Loc.Line })
	return out, nil
}

func splitOption(s string) (opt, arg string) {
	if strings.HasPrefix(s, "--") {
		if i := strings.IndexAny(s, "= \t"); i > 0 {
			return s[:i], strings.TrimSpace(s[i+1:])
		}
		return s, ""
	}
	if len(s) > 2 && s[2] != ' ' && s[2] != '\t' { // -rfile
		return s[:2], strings.TrimSpace(s[2:])
	}
	if i := strings.IndexAny(s, " \t"); i > 0 {
		return s[:i], strings.TrimSpace(s[i+1:])
	}
	return s, ""
}

// parseVia extracts the "# via" parents of pip-compile / uv pip compile output.
func parseVia(comments []string) []string {
	var out []string
	in := false
	for _, c := range comments {
		c = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(c), "#"))
		switch {
		case strings.HasPrefix(c, "via "):
			out = append(out, strings.TrimSpace(strings.TrimPrefix(c, "via ")))
			in = false
		case c == "via":
			in = true
		case in && c != "":
			out = append(out, c)
		}
	}
	return out
}

// requirementLine parses one requirement or direct reference.
// The scope, group and confidence of the result depend on the file NAME (requirements-dev.txt) and are therefore set by the assembler.
func requirementLine(out *manifests.Parsed, line int, text string) (manifests.Dependency, bool) {
	isRef := strings.Contains(text, "://") || strings.HasPrefix(text, ".") || strings.HasPrefix(text, "/") || strings.HasPrefix(text, "file:") || strings.HasPrefix(text, "git+")
	if isRef && !strings.Contains(strings.SplitN(text, " @ ", 2)[0], " ") && !strings.Contains(text, " @ ") {
		name := ""
		if m := eggFragment.FindStringSubmatch(text); m != nil {
			name = m[1]
		} else if m := wheelName.FindStringSubmatch(strings.SplitN(strings.SplitN(text, "#", 2)[0], "?", 2)[0]); m != nil {
			name = m[1]
		}
		if name == "" {
			out.Diagnostics = append(out.Diagnostics, diag("python.unnamed-requirement", line, "requirement %q has no package name", manifests.CleanText(redactURL(text), 80)))
			return manifests.Dependency{}, false
		}
		d := manifests.Dependency{Target: idOf(name), Line: int32(line)}
		d.SetTargetDisplay(cleanName(name))
		kind := sourceKindOfURL(text)
		ref := redactURL(text)
		if kind == manifests.SourcePath {
			ref = pathOfURL(text)
		}
		d.SetSource(kind, ref)
		return d, true
	}
	r, ok := ParseRequirement(text)
	if !ok {
		out.Diagnostics = append(out.Diagnostics, diag("python.requirement-invalid", line, "cannot parse requirement %q", manifests.CleanText(redactURL(text), 80)))
		return manifests.Dependency{}, false
	}
	return depFrom(r, manifests.ScopeUnknown, "", line), true
}
