func TestRouteLiteralCoversThePublicAndAdminPrefixes(t *testing.T) {
	for _, s := range []string{"/metrics", "/debug/pprof/", "/dashboard", "/groups/x", "/badges/x", "/repos/a/docs/b", "/pages/x", "/robots.txt", "/sitemap.xml",
		"/favicon.svg", "/manifest.webmanifest", "/theme-init.js", "/_frame/mermaid.html", "/llms.txt", "/livez", "/readyz", "/webhooks/github", "/csp-reports"} {
		if !archtest.RouteLiteral(s) {
			t.Errorf("%q is a route of the portal but the rule does not see it", s)
		}
	}
	for _, s := range []string{"/", "/tmp/x", "/run/secrets/x", "/etc/scp/config.yaml", "api/v1", "https://x/api", "/data/scp.db"} {
		if archtest.RouteLiteral(s) {
			t.Errorf("%q is not a route", s)
		}
	}
}

func TestScanSourceRules(t *testing.T) {
	files := map[string]string{
		"internal/commits/ok.go":         "package commits\n\n// TODO(#12) cap the page size\nconst api = \"api/v1\"\n",
		"internal/commits/bad.go":        "package commits\n\n// TODO: fix\nfunc f() string { return \"/repos/\" + \"x\" }\n",
		"internal/routes/builders.go":    "package routes\n\nfunc Repo(s string) string { return \"/repos/\" + s }\n",
		"internal/commits/gen.gen.go":    "package commits\n\nconst x = \"/api/v1/commits\"\n",
		"internal/commits/ok_test.go":    "package commits\n\nimport \"testing\"\n\nfunc TestA(t *testing.T) { t.Skip(\"flaky on arm, see https://github.com/Cantara/source-code-portal/issues/42\") }\n",
		"internal/commits/bad_test.go":   "package commits\n\nimport \"testing\"\n\nfunc TestB(t *testing.T) { t.Skip(\"later\") }\nfunc TestC(t *testing.T) { t.SkipNow() }\n",
		"internal/commits/route_test.go": "package commits\n\nconst u = \"/api/v1/x\" // test files may hold literals\n",
		// upstream clients speak other servers' paths (GitHub REST, Jenkins, the fake GitHub): exempt
		"internal/github/client.go":          "package github\n\nfunc path(o, r string) string { return \"/repos/\" + o + \"/\" + r }\n",
		"internal/integrations/jenkins/j.go": "package jenkins\n\nconst probe = \"/api/json\"\n",
		"cmd/fakegithub/main.go":             "package main\n\nconst r = \"/repos/x\"\n",
		// generated code is recognized by the toolchain's rule even when a build constraint comes first
		"internal/commits/gen3.go": "//go:build !devtools\n\n// Code generated by oapi-codegen. DO NOT EDIT.\n\npackage commits\n\nconst y = \"/api/v1/commits\"\n",
		// a package that happens to be called tools or dist is product code: scanned; the top-level tools module and dist are not
		// A-30: a file that builds routes.Route rows holds the patterns by definition; a file that only imports routes does not
		"internal/overview/table.go":       "package overview\n\nimport \"github.com/cantara/source-code-portal/internal/routes\"\n\nvar _ = []routes.Route{{Pattern: \"/api/v1/site\"}}\n",
		"internal/overview/plain.go":       "package overview\n\nimport \"github.com/cantara/source-code-portal/internal/routes\"\n\nvar _ = routes.Repo\n\nconst p = \"/api/v1/site\"\n",
		"internal/httpapi/apitest/spec.go": "package apitest\n\nconst p = \"/api/v1/site\"\n",
		"internal/commits/tools/t.go":      "package tools\n\nconst z = \"/commits/x\"\n",
		"tools/apicheck/main.go":           "package main\n\nconst z = \"/commits/x\"\n",
		"dist/x.go":                        "package dist\n\nconst z = \"/commits/x\"\n",
	}
	dir := t.TempDir()
	for name, src := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	vs, err := archtest.ScanSource(dir)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]int{}
	for _, v := range vs {
		got[v.Code+" "+v.Pkg]++
	}
	want := map[string]int{
		"todo internal/commits/bad.go":              1,
		"route-literal internal/commits/bad.go":     1,
		"skip internal/commits/bad_test.go":         2,
		"route-literal internal/commits/tools/t.go": 1,
		"route-literal internal/overview/plain.go":  1,
	}
	if len(got) != len(want) {
		t.Fatalf("got %v want %v\n%s", got, want, strings.Join(func() (o []string) {
			for _, v := range vs {
				o = append(o, v.String())
			}
			return
		}(), "\n"))
	}
	for k, n := range want {
		if got[k] != n {
			t.Errorf("%s: got %d want %d", k, got[k], n)
		}
	}
}
