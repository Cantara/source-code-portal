package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

// runAliases writes the hand-maintained-by-generator alias file of one feature api package (design 07, 2.3.5).
//
// A feature may not import httpapi/openapi (architecture 5.2: it is not in K4), but the generated <feature>api package
// is allowed to (rank 1), and the feature may import its own <feature>api. The file re-exports, as type aliases and
// constants of the feature package, every common schema, every enum constant of common.yaml and the header struct of the
// shared 304 response, so a handler builds `commitsapi.Commit{...}` and never names the shared package.
func runAliases(args []string) int {
	fs := flag.NewFlagSet("aliases", flag.ContinueOnError)
	common := fs.String("common", "", "common.yaml")
	gen := fs.String("gen", "", "common.gen.go (generated from common.yaml)")
	module := fs.String("module", "", "module path of the repository")
	pkg := fs.String("pkg", "", "package name of the feature api package, e.g. commitsapi")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	l := openapi3.NewLoader()
	doc, err := l.LoadFromFile(*common)
	if err != nil {
		fmt.Fprintln(os.Stderr, "aliases:", err)
		return 1
	}
	schema := map[string]bool{}
	for n := range doc.Components.Schemas {
		schema[n] = true
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, *gen, nil, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, "aliases:", err)
		return 1
	}
	types := map[string]bool{}
	consts := map[string]string{} // const name -> type
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range g.Specs {
			switch x := sp.(type) {
			case *ast.TypeSpec:
				if schema[x.Name.Name] || x.Name.Name == "NotModifiedResponseHeaders" {
					types[x.Name.Name] = true
				}
			case *ast.ValueSpec:
				if g.Tok != token.CONST || x.Type == nil {
					continue
				}
				if id, ok := x.Type.(*ast.Ident); ok && schema[id.Name] {
					for _, n := range x.Names {
						consts[n.Name] = id.Name
					}
				}
			}
		}
	}
	for n := range schema {
		if !types[n] {
			fmt.Fprintf(os.Stderr, "aliases: schema %s has no type in %s\n", n, *gen)
			return 1
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by `apicheck aliases`; DO NOT EDIT.\n// Source: internal/httpapi/openapi/common.yaml. Rule: a feature never imports httpapi/openapi (architecture 5.2); it names these aliases.\n\npackage %s\n\nimport \"%s/internal/httpapi/openapi\"\n\n", *pkg, *module)
	b.WriteString("type (\n")
	tn := make([]string, 0, len(types))
	for n := range types {
		tn = append(tn, n)
	}
	sort.Strings(tn)
	for _, n := range tn {
		fmt.Fprintf(&b, "\t%s = openapi.%s\n", n, n)
	}
	b.WriteString(")\n")
	if len(consts) > 0 {
		b.WriteString("\nconst (\n")
		cn := make([]string, 0, len(consts))
		for n := range consts {
			cn = append(cn, n)
		}
		sort.Strings(cn)
		for _, n := range cn {
			fmt.Fprintf(&b, "\t%s = openapi.%s\n", n, n)
		}
		b.WriteString(")\n")
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "aliases:", err)
		return 1
	}
	os.Stdout.Write(src)
	return 0
}
