// Command chromacss writes the CSS for the token classes the docs pipeline puts on highlighted code, light and dark. Each theme is
// scoped on its own, so a token the dark style leaves unset takes the dark text colour rather than the light style's.
// `go generate ./web` runs it into web/src/styles/chroma.css.
package main

import (
	"bytes"
	"fmt"
	"os"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: chromacss <out.css>")
		os.Exit(2)
	}
	f := chromahtml.New(chromahtml.WithClasses(true))
	var b bytes.Buffer
	b.WriteString("/* Code generated by internal/docs/chromacss; DO NOT EDIT. */\n")
	for _, theme := range []struct{ scope, style string }{{":root:not(.dark) .doc", "github"}, {".dark .doc", "github-dark"}} {
		var css bytes.Buffer
		if err := f.WriteCSS(&css, styles.Get(theme.style)); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		for _, line := range bytes.Split(bytes.TrimSpace(css.Bytes()), []byte("\n")) {
			// Rules start with "/* name */ .chroma ..."; scope them to the document container of the theme.
			i := bytes.Index(line, []byte(".chroma"))
			if i < 0 {
				continue // the standalone .bg rule; the document styles its own background
			}
			line = append(append(append([]byte{}, line[:i]...), []byte(theme.scope+" ")...), line[i:]...)
			b.Write(line)
			b.WriteByte('\n')
		}
	}
	if err := os.WriteFile(os.Args[1], b.Bytes(), 0o644); err != nil { //nolint:gosec // a source file
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
